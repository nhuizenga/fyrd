namespace Fyrd.Core.Hub;

/// <summary>
/// The block the owner pastes into the setup script of the cloud environment Fyrd uses. A setup script runs as root
/// before Claude Code starts; the block installs the fyrd plugin from its public repository with the Claude Code CLI,
/// so new sessions (and their subagents) list the plugin's skills, among them the default session skills, as
/// <c>fyrd:&lt;name&gt;</c>.
/// <para>
/// The block is the same for every set of skills: it holds no skill text, so editing a skill never makes it out of
/// date. It is plain POSIX shell in one subshell that ends in <c>|| true</c>: it leaves no shell option or variable
/// behind, has no <c>exit</c>, and can't fail or end the script around it. Running it again is harmless: the CLI keeps
/// a marketplace or plugin that is already there, and the block then updates both.
/// </para>
/// </summary>
public static class SessionSkillScript
{
    public const string Begin = "# >>> fyrd plugin >>>";
    public const string End = "# <<< fyrd plugin <<<";

    /// <summary>The public repository the plugin is installed from, as <c>owner/repo</c> on GitHub.</summary>
    public const string Repository = "nhuizenga/fyrd";

    /// <summary>The plugin's id: plugin <c>fyrd</c> in the marketplace <c>fyrd</c> that <see cref="Repository"/> declares.</summary>
    public const string PluginId = "fyrd@fyrd";

    /// <summary>The prefix Claude Code gives a plugin's skills: <c>fyrd:stacked-pull-requests</c>.</summary>
    public const string SkillPrefix = "fyrd:";

    /// <summary>The block. It ends with a line end.</summary>
    public static string Render() => string.Join("\n",
        Begin,
        "# Generated by Fyrd (Settings, Session skills). Keep this block whole.",
        $"# It installs the fyrd Claude Code plugin from https://github.com/{Repository} for the sessions started here,",
        "# so they can load Fyrd's session skills. It never stops the rest of your setup script.",
        "(",
        "  set +e +u +C",
        "  if command -v claude >/dev/null 2>&1; then",
        $"    claude plugin marketplace add {Repository}",
        "    claude plugin marketplace update fyrd",
        $"    claude plugin install {PluginId} --scope user",
        $"    claude plugin update {PluginId}",
        "  else",
        "    echo 'fyrd: the claude command was not found, so the fyrd plugin is not installed' >&2",
        "  fi",
        ") || true",
        End,
        "");

    /// <summary>The name a session loads a plugin skill by.</summary>
    public static string PluginSkillName(string name) => SkillPrefix + name;
}
