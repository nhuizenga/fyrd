using System.Text;

namespace Fyrd.Core.Hub;

/// <summary>
/// Renders the block the owner pastes into the setup script of the cloud environment Fyrd uses. A setup script runs as
/// root before Claude Code starts and can't reach Fyrd, so the block holds every skill's text and writes it under
/// <c>/root/.claude/skills</c>, where new sessions (and their subagents) find it.
/// <para>
/// The block is plain POSIX shell in one subshell that ends in <c>|| true</c>: it uses no network, leaves no shell
/// option or variable behind, has no <c>exit</c>, and can't fail or end the script around it. Running it again gives
/// the same files. It keeps a manifest of the skills it wrote and removes only skills an earlier block listed there
/// that are gone now, and it writes the hash of the skills last, as the mark of a complete run.
/// </para>
/// </summary>
public static class SessionSkillScript
{
    public const string BeginPrefix = "# >>> fyrd session skills ";
    public const string End = "# <<< fyrd session skills <<<";

    /// <summary>Where the skills go in a cloud session.</summary>
    public const string SkillsDir = "/root/.claude/skills";

    /// <summary>The manifest (the names the block installed) and the hash marker.</summary>
    public const string ManifestFile = "/root/.claude/fyrd-session-skills/manifest", HashFile = "/root/.claude/fyrd-session-skills/hash";

    private const string Delimiter = "FYRD_SKILL_EOF";

    public static string Begin(string hash) => $"{BeginPrefix}{hash} >>>";

    /// <summary>The block for these skills, ordered by name, named by <see cref="SessionSkills.Hash(IEnumerable{SessionSkill})"/>.</summary>
    public static string Render(IReadOnlyList<SessionSkill> skills)
    {
        var ordered = skills.Select(SessionSkills.Normalize).OrderBy(s => s.Name, StringComparer.Ordinal).ToList();
        var hash = SessionSkills.Hash(ordered);
        var names = ordered.Select(s => s.Name).ToList();
        var sb = new StringBuilder();
        void Line(string line = "") => sb.Append(line).Append('\n');

        Line(Begin(hash));
        Line("# Generated by Fyrd (Settings, Session skills). Keep this block whole; when Fyrd shows a new one, replace it, markers included.");
        Line($"# It writes Fyrd's session skills to {SkillsDir}, removes the ones an earlier block wrote that are gone now,");
        Line("# uses no network and never stops the rest of your setup script.");
        Line("(");
        Line("  set +e +u");
        // FYRD_CLAUDE_DIR is for trying the block out somewhere else; a cloud environment doesn't set it.
        Line("  fyrd_claude=\"${FYRD_CLAUDE_DIR:-/root/.claude}\"");
        Line("  fyrd_skills=\"$fyrd_claude/skills\"");
        Line("  fyrd_state=\"$fyrd_claude/fyrd-session-skills\"");
        Line($"  fyrd_keep=\" {string.Join(' ', names)} \"");
        Line("  if [ -f \"$fyrd_state/manifest\" ]; then");
        Line("    while IFS= read -r fyrd_old || [ -n \"$fyrd_old\" ]; do");
        Line("      case \"$fyrd_old\" in fyrd-*) ;; *) continue ;; esac");
        Line("      case \"$fyrd_old\" in *[!a-z0-9-]*) continue ;; esac");
        Line("      case \"$fyrd_keep\" in *\" $fyrd_old \"*) continue ;; esac");
        Line("      rm -rf \"$fyrd_skills/$fyrd_old\"");
        Line("    done < \"$fyrd_state/manifest\"");
        Line("  fi");
        Line("  mkdir -p \"$fyrd_state\" \"$fyrd_skills\"");
        Line(names.Count == 0
            ? "  : > \"$fyrd_state/manifest\""
            : $"  printf '%s\\n' {string.Join(' ', names)} > \"$fyrd_state/manifest\"");
        foreach (var s in ordered)
        {
            var file = SkillFile(s);
            var delimiter = DelimiterFor(file);
            Line($"  mkdir -p \"$fyrd_skills/{s.Name}\"");
            Line($"  cat > \"$fyrd_skills/{s.Name}/SKILL.md\" <<'{delimiter}'");
            sb.Append(file);
            Line(delimiter);
        }
        Line($"  printf '%s\\n' {hash} > \"$fyrd_state/hash\"");
        Line(") || true");
        Line(End);
        return sb.ToString();
    }

    /// <summary>The <c>SKILL.md</c> a session reads: front matter with only <c>name</c> and <c>description</c>, then the body. Ends with a line end.</summary>
    public static string SkillFile(SessionSkill skill) =>
        $"---\nname: {skill.Name}\ndescription: {YamlString(skill.Description)}\n---\n\n{skill.Body}\n";

    /// <summary>A double-quoted YAML scalar, so a colon, a hash or a quote in the description can't change the front matter.</summary>
    private static string YamlString(string s) => "\"" + s.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";

    /// <summary>A here-document delimiter that is no line of the text, so the text can't end its own here-document.</summary>
    public static string DelimiterFor(string text)
    {
        var lines = text.Split('\n').ToHashSet(StringComparer.Ordinal);
        var delimiter = Delimiter;
        for (var n = 1; lines.Contains(delimiter); n++) delimiter = $"{Delimiter}_{n}";
        return delimiter;
    }
}
